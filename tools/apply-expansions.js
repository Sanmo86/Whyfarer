// tools/apply-expansions.js
// One-off dev script: splices the two new paragraphs from expansions.js into
// each article's `content` array (just before the closing paragraph), then
// rewrites content.en.js / content.es.js as valid JS source, preserving the
// original per-article field order and template-literal formatting.
'use strict';

const fs = require('fs');
const path = require('path');
const { META } = require('./meta.js');
const { ARTICLES_EN } = require('./content.en.js');
const { ARTICLES_ES } = require('./content.es.js');
const { EXPANSIONS } = require('./expansions.js');

const ROOT = __dirname;

function tl(str) {
  if (/`|\$\{/.test(str)) {
    throw new Error('String contains a backtick or ${ — cannot safely wrap as template literal:\n' + str.slice(0, 80));
  }
  return '`' + str + '`';
}

function serializeArticle(a) {
  const contentItems = a.content.map(function (p) { return tl(p); }).join(',\n');
  return `{
  country: ${tl(a.country)},
  kicker: ${tl(a.kicker)},
  title: ${tl(a.title)},
  dek: ${tl(a.dek)},
  alt: ${tl(a.alt)},
  readTime: ${tl(a.readTime)},
  pullQuote: ${tl(a.pullQuote)},
  fact: ${tl(a.fact)},
  content: [
${contentItems}
  ]
}`;
}

function build(varName, headerComment, articles, expansionsForLocale) {
  const blocks = META.map(function (m, i) {
    const a = Object.assign({}, articles[i]);
    a.content = a.content.slice();
    const additions = expansionsForLocale[m.slug];
    if (!additions || additions.length !== 2) {
      throw new Error('Missing expansions for slug: ' + m.slug);
    }
    // Insert the two new paragraphs just before the final (closing) paragraph.
    const last = a.content.pop();
    a.content.push(additions[0], additions[1], last);
    return `// ${i + 1} — ${m.slug}\n${serializeArticle(a)}`;
  });

  return `${headerComment}
'use strict';

const ${varName} = [

${blocks.join(',\n\n')}

];

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { ${varName} };
}
`;
}

const enHeader = `// tools/content.en.js
// English content (primary locale), in the same order as tools/meta.js.
// Regenerated by tools/apply-expansions.js — hand-edit paragraphs freely,
// but if you re-run that script it will re-splice from expansions.js.`;

const esHeader = `// tools/content.es.js
// Spanish content, in the same order as tools/meta.js.
// Regenerated by tools/apply-expansions.js — hand-edit paragraphs freely,
// but if you re-run that script it will re-splice from expansions.js.`;

fs.writeFileSync(path.join(ROOT, 'content.en.js'), build('ARTICLES_EN', enHeader, ARTICLES_EN, EXPANSIONS.en));
fs.writeFileSync(path.join(ROOT, 'content.es.js'), build('ARTICLES_ES', esHeader, ARTICLES_ES, EXPANSIONS.es));

console.log('Done. Rewrote content.en.js and content.es.js with 2 extra paragraphs per article.');
